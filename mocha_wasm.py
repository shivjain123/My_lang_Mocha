_HTML_MARK = "<!-- mocha-generated: delete this line and `mocha wasm` will stop overwriting this page -->"

def write_html(output_wasm, sigs):
    """Write <name>.html next to the wasm: one input per parameter of each exported function.
    A page without the marker comment is the user's own, so it is left alone."""
    import json
    base = os.path.splitext(output_wasm)[0]
    html_path = base + ".html"
    if os.path.exists(html_path):
        with open(html_path, encoding="utf-8") as f:
            if _HTML_MARK not in f.read():
                print(f"  🛡️  Kept your {os.path.basename(html_path)} (no generated-page marker, not overwriting)")
                return None
    funcs = [{"name": n, "params": [list(p) for p in ps], "ret": r} for n, (ps, r) in sigs.items()]
    page = (_HTML_PAGE.replace("__TITLE__", os.path.basename(base))
                      .replace("__JS__", os.path.basename(base) + ".js")
                      .replace("__FUNCS__", json.dumps(funcs)))
    with open(html_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(_HTML_MARK + "\n" + page)
    return html_path

def main():
    ap = argparse.ArgumentParser(description="Build a Mocha program as WebAssembly")
    ap.add_argument("program_ll")
    ap.add_argument("--lib", action="append", default=[], help="library .ll file (repeat)")
    ap.add_argument("--export", action="append", required=True, help="function to expose to JS (repeat)")
    ap.add_argument("-o", "--output")
    a = ap.parse_args()
    out = a.output or os.path.splitext(a.program_ll)[0] + ".wasm"
    sys.exit(0 if compile_wasm(a.program_ll, out, a.export, a.lib) else 1)


if __name__ == "__main__":
    main()