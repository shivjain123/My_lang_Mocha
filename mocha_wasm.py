"""
mocha_wasm.py - build a Mocha program as a WebAssembly (wasm32-wasi) module.

Standalone for now:
  python mocha_wasm.py cape_demo.ll --lib lib\\mocha-math.ll --lib lib\\mocha-meteoro.ll --export cape_demo
Later, the compiler can import compile_wasm() to support `mocha --wasm`.
Needs the C runtime to contain the MOCHA_WASM guards and the mocha_malloc64 shim.
"""
import argparse, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))


_SHIMS = {"malloc": "mocha_malloc64", "rc_alloc": "mocha_rc_alloc64", "rc_count": "mocha_rc_count64"}

def _patch_ir(src, dst):
    """wasm32's size_t is 32-bit, but the IR declares these functions with i64 sizes. Route them through adapters."""
    with open(src, encoding="utf-8") as f:
        text = f.read()
    text = re.sub(r"@(malloc|rc_alloc|rc_count)\b", lambda m: "@" + _SHIMS[m.group(1)], text)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

_JS_LOADER = r'''// Generated by `mocha wasm` - loads __WASM__ in the browser. No other glue needed.
// Mocha `int`/`float` arrive as JS numbers; `vast` (64-bit) arrives as BigInt.
export async function load(url = new URL('__WASM__', import.meta.url), { onOutput = (line) => console.log(line) } = {}) {
  let mem;
  let buf = '';
  const dec = new TextDecoder();
  const emit = (text) => {
    buf += text;
    let i;
    while ((i = buf.indexOf('\n')) >= 0) { onOutput(buf.slice(0, i)); buf = buf.slice(i + 1); }
  };
  const flush = () => { if (buf) { onOutput(buf); buf = ''; } };
  const wasi = {
    fd_write(fd, iovs, iovsLen, nwrittenPtr) {
      const dv = new DataView(mem.buffer);
      let total = 0;
      for (let i = 0; i < iovsLen; i++) {
        const ptr = dv.getUint32(iovs + i * 8, true), len = dv.getUint32(iovs + i * 8 + 4, true);
        emit(dec.decode(new Uint8Array(mem.buffer, ptr, len)));
        total += len;
      }
      dv.setUint32(nwrittenPtr, total, true);
      return 0;
    },
    environ_sizes_get(countPtr, sizePtr) { const dv = new DataView(mem.buffer); dv.setUint32(countPtr, 0, true); dv.setUint32(sizePtr, 0, true); return 0; },
    args_sizes_get(countPtr, sizePtr)    { const dv = new DataView(mem.buffer); dv.setUint32(countPtr, 0, true); dv.setUint32(sizePtr, 0, true); return 0; },
    random_get(ptr, len) { crypto.getRandomValues(new Uint8Array(mem.buffer, ptr, len)); return 0; },
    clock_time_get(id, precision, outPtr) { new DataView(mem.buffer).setBigUint64(outPtr, BigInt(Date.now()) * 1000000n, true); return 0; },
    proc_exit(code) { throw new Error('Mocha exited with code ' + code); },
  };
  const imports = { wasi_snapshot_preview1: new Proxy(wasi, { get: (t, name) => t[name] || (() => 0) }) };
  const bytes = await (await fetch(url)).arrayBuffer();
  const { instance } = await WebAssembly.instantiate(bytes, imports);
  mem = instance.exports.memory;
  if (instance.exports._initialize) instance.exports._initialize();
  return { ...instance.exports, flush };
}
'''

def write_js_loader(output_wasm):
    js_path = os.path.splitext(output_wasm)[0] + ".js"
    with open(js_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(_JS_LOADER.replace("__WASM__", os.path.basename(output_wasm)))
    return js_path

def compile_wasm(program_ll, output_wasm, exports, lib_lls=(), zig_path=None,
                 zig_lib_dir=None, runtime_c=None, build_dir=None):
    zig_path    = zig_path    or os.path.join(HERE, "zig.exe" if os.name == "nt" else "zig")
    zig_lib_dir = zig_lib_dir or os.path.join(HERE, "zig-lib")
    runtime_c   = runtime_c   or os.path.join(HERE, "mocha_runtime.c")
    build_dir   = build_dir   or os.path.join(HERE, "wasm_build")
    os.makedirs(build_dir, exist_ok=True)

    env = os.environ.copy()
    env["ZIG_LIB_DIR"] = zig_lib_dir

    # Release builds drop all debug info (it was 97% of the file size). Set MOCHA_WASM_DEBUG=1 to keep it.
    debug = bool(os.environ.get("MOCHA_WASM_DEBUG"))
    cc = [zig_path, "cc", "-target", "wasm32-wasi", "-O2"] + ([] if debug else ["-g0"])

    warnings = []

    def step(cmd, what):
        r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", env=env)
        if r.returncode != 0:
            print(f"  ❌ {what} failed:\n{r.stderr}")
            return False
        warnings.extend(l.strip() for l in r.stderr.splitlines()
                        if "function signature mismatch" in l)
        return True

    # 1. the C runtime (cached; rebuilt only when mocha_runtime.c changes)
    rt_obj = os.path.join(build_dir, "rt_wasm_debug.o" if debug else "rt_wasm_release.o")
    if not os.path.exists(rt_obj) or os.path.getmtime(runtime_c) > os.path.getmtime(rt_obj):
        print("  🔧 Building the wasm runtime (first time, or the runtime changed)...")
        if not step(cc + ["-c", runtime_c, "-o", rt_obj], "runtime compile"):
            return False
    else:
        print("  ⚡ wasm runtime cached")

    # 2. libraries + the program: patch the IR, then compile each to a wasm object
    objs = []
    for ll in list(lib_lls) + [program_ll]:
        name = os.path.splitext(os.path.basename(ll))[0]
        patched = os.path.join(build_dir, name + ".ll")
        obj = os.path.join(build_dir, name + ".o")
        _patch_ir(ll, patched)
        if not step(cc + ["-c", patched, "-o", obj], f"compile {name}"):
            return False
        objs.append(obj)

    # 3. link as a reactor module (a library the browser calls into, not a program with main)
    link = [zig_path, "cc", "-target", "wasm32-wasi", "-mexec-model=reactor"]
    link += ["-Wl,--gc-sections"] + ([] if debug else ["-Wl,--strip-all"])
    link += [f"-Wl,--export={e}" for e in exports]
    link += objs + [rt_obj, "-o", output_wasm]
    if not step(link, "link"):
        return False

    for w in sorted(set(warnings)):
        print("  ⚠️ ", w)
    print(f"  ✅ Wrote {output_wasm} ({os.path.getsize(output_wasm) // 1024} KB)")
    js_path = write_js_loader(output_wasm)
    print(f"  📄 Wrote {js_path} (browser loader)")
    return True

SCALARS = {"int", "float", "vast", "bool"}
_FUNC = re.compile(r"^function\s+(\w+)\s*\(([^)]*)\)\s*(?:->\s*([\w\[\]]+))?", re.M)

def auto_exports(source):
    """Public (column-0) functions whose parameters and return type are plain numbers."""
    exports, skipped = [], []
    for m in _FUNC.finditer(source):
        name, params, ret = m.group(1), m.group(2), (m.group(3) or "null")
        if name == "main":
            continue
        ptypes = [p.split(":", 1)[1].split("=")[0].strip() for p in params.split(",") if ":" in p]
        if all(t in SCALARS for t in ptypes) and ret in (SCALARS | {"null"}):
            exports.append(name)
        else:
            skipped.append(name)
    return exports, skipped

def main():
    ap = argparse.ArgumentParser(description="Build a Mocha program as WebAssembly")
    ap.add_argument("program_ll")
    ap.add_argument("--lib", action="append", default=[], help="library .ll file (repeat)")
    ap.add_argument("--export", action="append", required=True, help="function to expose to JS (repeat)")
    ap.add_argument("-o", "--output")
    a = ap.parse_args()
    out = a.output or os.path.splitext(a.program_ll)[0] + ".wasm"
    sys.exit(0 if compile_wasm(a.program_ll, out, a.export, a.lib) else 1)


if __name__ == "__main__":
    main()